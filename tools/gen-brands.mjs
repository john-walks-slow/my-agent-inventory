/** 相对亮度（0..1） */
function luminance(hex) {
  const n = parseInt(hex.slice(1), 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((c) => c / 255);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** 浏览器内栅格化：SVG path → 160×160 → 盒降采样 16×16 墨点矩阵 */
async function rasterize(page, svgPath, hex) {
  return page.evaluate(
    (svgPath, hex) => {
      const HI = 160; // 16 的 10 倍，每格 10×10 采样
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="${svgPath}" fill="#${hex}"/></svg>`;
      const url = `data:image/svg+xml;base64,${btoa(svg)}`;
      const img = new Image();
      img.src = url;
      return new Promise((resolve) => {
        img.onload = () => {
          const canvas = document.createElement('canvas');
          canvas.width = HI;
          canvas.height = HI;
          const ctx = canvas.getContext('2d', { willReadFrequently: true });
          ctx.drawImage(img, 0, 0, HI, HI);
          const data = ctx.getImageData(0, 0, HI, HI).data;
          const grid = [];
          for (let y = 0; y < 16; y++) {
            const row = [];
            for (let x = 0; x < 16; x++) {
              let ink = 0;
              for (let sy = 0; sy < 10; sy++) {
                for (let sx = 0; sx < 10; sx++) {
                  const i = ((y * 10 + sy) * HI + x * 10 + sx) * 4 + 3;
                  if (data[i] > 127) ink++;
                }
              }
              row.push(ink >= 50 ? 1 : 0); // ≥50% 覆盖才算墨
            }
            grid.push(row);
          }
          resolve(grid);
        };
        img.onerror = () => resolve(null);
      });
    },
    svgPath,
    hex
  );
}

/** 墨点矩阵 → 像素 SVG：内部品牌色 + 外缘对比描边 */
function gridToSvg(grid, hex) {
  const outline = luminance(hex) < 0.5 ? '#ffffff' : '#101010';
  const at = (x, y) => (x < 0 || y < 0 || x > 15 || y > 15 ? 0 : grid[y][x]);
  const rects = [];
  for (let y = 0; y < 16; y++) {
    for (let x = 0; x < 16; x++) {
      if (!grid[y][x]) continue;
      const isEdge = !at(x - 1, y) || !at(x + 1, y) || !at(x, y - 1) || !at(x, y + 1);
      rects.push({ x, y, fill: isEdge ? outline : `#${hex}` });
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">
  <!-- generated by tools/gen-brands.mjs (simple-icons) -->
  <g>
${rects.map((r) => `    <rect x="${r.x}" y="${r.y}" width="1" height="1" fill="${r.fill}"/>`).join('\n')}
  </g>
</svg>
`;
}

async function generateFromSimpleIcons() {
  const browser = await puppeteer.launch({
    executablePath: '/usr/bin/google-chrome',
    args: ['--no-sandbox', '--disable-dev-shm-usage'],
  });
  const page = await browser.newPage();
  const results = [];
  for (const [key, exportName] of Object.entries(SIMPLE_ICONS)) {
    const icon = icons[exportName] ?? icons[`si${exportName}`];
    if (!icon) throw new Error(`simple-icons 无 ${exportName}（${key}）`);
    const grid = await rasterize(page, icon.path, icon.hex);
    if (!grid) throw new Error(`${key} 栅格化失败`);
    const file = path.join(outDir, `${key}.svg`);
    writeFileSync(file, gridToSvg(grid, icon.hex));
    console.log(`ok ${file}（${icon.title} #${icon.hex}）`);
    results.push(key);
  }
  await browser.close();
  return results;
}

// ---- 2. 手绘字符画兜底（无 simple-icons 收录的品牌） ----

function toSvg(art, palette, key) {
  if (art.length !== 16 || art.some((row) => row.length !== 16)) {
    throw new Error(`${key}: 画布必须为 16×16`);
  }
  const rects = [];
  art.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      const ch = row[x];
      if (ch === '.') continue;
      const fill = palette[ch];
      if (!fill) throw new Error(`${key}: 字符 "${ch}" 无对应颜色`);
      rects.push(`    <rect x="${x}" y="${y}" width="1" height="1" fill="${fill}"/>`);
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">
  <!-- generated by tools/gen-brands.mjs (hand-drawn) -->
  <g>
${rects.join('\n')}
  </g>
</svg>
`;
}

