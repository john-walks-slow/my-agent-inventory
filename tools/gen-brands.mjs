#!/usr/bin/env node
// 品牌像素头像生成器（src/brands/<key>.svg，16×16 crispEdges SVG）。
//
// 两级来源：
// 1. simple-icons（CC0）正牌轮廓 → 160×160 栅格化 → 盒降采样 16×16 →
//    品牌色填充 + 自动对比描边（暗色品牌描白边、亮色品牌描黑边，
//    保证深浅主题底上都可读）。依赖 puppeteer-core 栅格化（须在仓库内运行）。
// 2. 无收录的品牌（dsh 自家、OpenAI 系商标未收录等）→ 手绘字符画。
//
// 用法：node tools/gen-brands.mjs
// 加新品牌：优先在 SIMPLE_ICONS 加 slug；无收录再画字符画。

